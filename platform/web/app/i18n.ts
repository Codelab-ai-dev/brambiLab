export type MessageKey = keyof (typeof messages)["es"];

export function t(locale: Locale, key: MessageKey): string {
  return messages[locale][key];
}

const months: Record<Locale, string[]> = {
  es: ["enero", "febrero", "marzo", "abril", "mayo", "junio", "julio", "agosto", "septiembre", "octubre", "noviembre", "diciembre"],
  en: ["January", "February", "March", "April", "May", "June", "July", "August", "September", "October", "November", "December"],
};

/**
 * Editorial date in America/Mexico_City (UTC-6 all year since 2022), formatted by hand so the
 * server and the browser always produce the same text (no ICU differences, no hydration mismatch).
 */
export function formatDay(locale: Locale, iso: string): string {
  const local = new Date(Date.parse(iso) - 6 * 3600_000);
  const d = local.getUTCDate(), m = months[locale][local.getUTCMonth()], y = local.getUTCFullYear();
  return locale === "es" ? `${d} de ${m} de ${y}` : `${m} ${d}, ${y}`;
}

/** ISO date (YYYY-MM-DD) of the same editorial day, for <time dateTime>. */
export function isoDay(iso: string): string {
  return new Date(Date.parse(iso) - 6 * 3600_000).toISOString().slice(0, 10);
}
